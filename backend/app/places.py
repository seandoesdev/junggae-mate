_INDEX = sorted(((alias, p) for p in PLACES for alias in (p[0], *p[1])), key=lambda x: len(x[0]), reverse=True)


def find(text: str) -> dict | None:
    """질문에서 가장 긴 지역 이름 하나. {name, region, lat, lng, radius_m}"""
    for alias, (name, _, region, lat, lng, radius) in _INDEX:
        if alias in text:
            return {"name": name, "region": region, "lat": lat, "lng": lng, "radius_m": radius}
    return None


def gu_center(gu: str) -> dict | None:
    if gu not in GU_CENTER:
        return None
    lat, lng = GU_CENTER[gu]
    return {"name": gu, "region": f"서울 {gu}", "lat": lat, "lng": lng, "radius_m": None}


def distance_m(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    """두 좌표 사이 거리 (하버사인, m)"""
    r = 6371000
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lng2 - lng1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))
